// Bundles the agent weekly report (src/lib/agentReport.js + agentReportPdf.js
// and the rent engine they ride on) into the agent-weekly-report edge
// function, so the Monday email draws the same PDF as the Reports download.
//
//   node scripts/build-agent-report.mjs          write the bundle
//   node scripts/build-agent-report.mjs --check  fail if it is out of date
//
// Run it after touching agentReport.js, agentReportPdf.js, rentEngine.js or
// tenancyUtils.js, and commit the bundle with the change. A test runs the
// --check path so a stale bundle fails CI.
import { build } from 'esbuild'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const OUT = path.join(root, 'supabase-functions/agent-weekly-report/report.bundle.js')
const BANNER = '// GENERATED by scripts/build-agent-report.mjs from src/lib/agentReport.js and\n// src/lib/agentReportPdf.js. Do not edit by hand.\n'

export async function bundleAgentReport() {
  const res = await build({
    stdin: {
      contents: "export { buildAgentReport } from './src/lib/agentReport.js'\nexport { drawAgentReportPdf, agentReportFilename, dateLong } from './src/lib/agentReportPdf.js'\n",
      resolveDir: root, sourcefile: 'agent-report-entry.js',
    },
    bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', charset: 'ascii',
    write: false, legalComments: 'none', logLevel: 'silent',
  })
  // esbuild leaves non-ASCII inside regex literals; escape everything so the
  // bundle is plain ASCII (it is pasted into deploy tooling). \uXXXX is valid
  // in strings, regexes and comments alike.
  const ascii = res.outputFiles[0].text.replace(/[^\x00-\x7f]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'))
  return BANNER + ascii
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const code = await bundleAgentReport()
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
    if (cur !== code) { console.error('agent-weekly-report bundle is stale: run node scripts/build-agent-report.mjs'); process.exit(1) }
    console.log('agent-weekly-report bundle is up to date')
  } else {
    writeFileSync(OUT, code)
    console.log('wrote', path.relative(root, OUT), code.length, 'bytes')
  }
}
