// Bundles the weekly portfolio summary (src/lib/weeklySummary.js and the rent
// engine, roles and compliance catalogue it rides on) into the weekly-summary
// edge function, so the Monday email uses the same rent engine as the Rent
// Tracker.
//
//   node scripts/build-weekly-summary.mjs          write the bundle
//   node scripts/build-weekly-summary.mjs --check  fail if it is out of date
//
// Run it after touching weeklySummary.js, rentEngine.js, tenancyUtils.js,
// api/roles.js or complianceCatalogue.js, and commit the bundle with the
// change. A test runs the --check path so a stale bundle fails CI.
import { build } from 'esbuild'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const OUT = path.join(root, 'supabase-functions/weekly-summary/summary.bundle.js')
const BANNER = '// GENERATED by scripts/build-weekly-summary.mjs from src/lib/weeklySummary.js.\n// Do not edit by hand.\n'

export async function bundleWeeklySummary() {
  const res = await build({
    stdin: {
      contents: "export { scopeCompanies, buildWeeklySummary, weeklySummaryEmail, weekStartFor } from './src/lib/weeklySummary.js'\n",
      resolveDir: root, sourcefile: 'weekly-summary-entry.js',
    },
    bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', charset: 'ascii',
    write: false, legalComments: 'none', logLevel: 'silent',
  })
  // Plain ASCII, as for the agent report bundle (pasted into deploy tooling).
  const ascii = res.outputFiles[0].text.replace(/[^\x00-\x7f]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'))
  return BANNER + ascii
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const code = await bundleWeeklySummary()
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
    if (cur !== code) { console.error('weekly-summary bundle is stale: run node scripts/build-weekly-summary.mjs'); process.exit(1) }
    console.log('weekly-summary bundle is up to date')
  } else {
    writeFileSync(OUT, code)
    console.log('wrote', path.relative(root, OUT), code.length, 'bytes')
  }
}
